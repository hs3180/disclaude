import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { execFileSync, spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { test } from 'node:test';
import { EventEmitter } from 'node:events';
import { inflateSync } from 'node:zlib';
import { buildPatch } from '../../bin/jupyter-patch.js';
import { deployTerminal } from '../../bin/jupyter-terminal.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const cli = join(root, 'bin/disclaude.js');
const run = (args, options = {}) =>
  execFileSync(process.execPath, [cli, 'jupyter', 'patch', ...args], {
    encoding: 'utf8',
    ...options,
  });
const sha = (data) => createHash('sha256').update(data).digest('hex');

function fixture() {
  const path = mkdtempSync(join(tmpdir(), 'jupyter-cli-'));
  mkdirSync(join(path, 'bin'));
  return path;
}

test('public CLI generates reproducible artifacts outside the checkout with no host Python or PATH tools', () => {
  const path = fixture();
  try {
    const options = { cwd: path, env: { ...process.env, PATH: '' } };
    const info = JSON.parse(run(['info'], options));
    assert.equal(info.target, 'jupyter_server_nbmodel');
    assert.equal(info.activation.hotApplySupported, false);
    assert.equal(info.activation.serverRestartRequired, true);
    const first = JSON.parse(run(['generate', '--output', join(path, 'first.pyz')], options));
    const second = JSON.parse(run(['generate', '--output', join(path, 'second.pyz')], options));
    assert.equal(first.sha256, second.sha256);
    assert.equal(first.sha256, sha(readFileSync(first.artifact)));
    assert.equal(first.manifestSha256, info.manifestSha256);
    assert.equal(readFileSync(first.artifact + '.sha256', 'utf8').split(' ')[0], first.sha256);
    writeFileSync(join(path, 'owned.pyz'), 'existing-user-file');
    const refused = spawnSync(
      process.execPath,
      [cli, 'jupyter', 'patch', 'generate', '--output', join(path, 'owned.pyz')],
      options
    );
    assert.notEqual(refused.status, 0);
    assert.equal(readFileSync(join(path, 'owned.pyz'), 'utf8'), 'existing-user-file');
  } finally {
    rmSync(path, { recursive: true, force: true });
  }
});

test('invalid hosts, hot activation and missing restart are refused before SSH', () => {
  const path = fixture(),
    receipt = join(path, 'ssh-called');
  try {
    writeFileSync(
      join(path, 'bin/ssh'),
      `#!${process.execPath}\nrequire('fs').writeFileSync(${JSON.stringify(receipt)}, 'called');`,
      { mode: 0o755 }
    );
    for (const args of [
      ['apply', '--ssh', 'fixture'],
      ['rollback', '--ssh', 'fixture'],
      ['apply', '--ssh', 'fixture', '--hot', '--restart'],
      ['prepare', '--ssh', '-oProxyCommand=touch injected'],
      ['prepare', '--ssh', 'fixture;touch injected'],
      ['prepare', '--ssh', 'fixture', '--restart'],
      ['prepare', '--ssh', 'fixture', '--state-dir', 'relative-state'],
      ['apply', '--jupyter', 'configured', '--restart'],
      ['rollback', '--jupyter', 'configured', '--stopped'],
      ['prepare', '--jupyter', 'configured', '--ssh', 'fixture'],
      ['prepare', '--jupyter', 'configured', '--container', 'chosen'],
    ]) {
      const result = spawnSync(process.execPath, [cli, 'jupyter', 'patch', ...args], {
        encoding: 'utf8',
        cwd: path,
        env: { ...process.env, PATH: join(path, 'bin') },
      });
      assert.notEqual(result.status, 0, args.join(' '));
      assert.equal(existsSync(receipt), false);
    }
  } finally {
    rmSync(path, { recursive: true, force: true });
  }
});

test('SSH transport streams the generated bytes and quotes a remote state path without shell evaluation', () => {
  const path = fixture(),
    receipt = join(path, 'received.json'),
    marker = join(path, 'injected');
  try {
    writeFileSync(
      join(path, 'bin/ssh'),
      `#!${process.execPath}
const fs=require('fs'), cp=require('child_process');
const result=cp.spawnSync('/bin/sh', ['-c', process.argv.at(-1)], {input:fs.readFileSync(0),stdio:['pipe','pipe','pipe']});
process.stdout.write(result.stdout); process.stderr.write(result.stderr); process.exit(result.status);
`,
      { mode: 0o755 }
    );
    writeFileSync(
      join(path, 'bin/python3'),
      `#!${process.execPath}
const fs=require('fs'), crypto=require('crypto');
const data=fs.readFileSync(0), args=process.argv.slice(2);
fs.writeFileSync(${JSON.stringify(receipt)}, JSON.stringify({args,sha256:crypto.createHash('sha256').update(data).digest('hex')}));
console.log(JSON.stringify({transported:true}));
`,
      { mode: 0o755 }
    );
    const state = `/owned/path with spaces/'$(touch ${marker})`;
    const options = { cwd: path, env: { ...process.env, PATH: join(path, 'bin') } };
    assert.equal(
      JSON.parse(run(['prepare', '--ssh', 'fixture', '--state-dir', state], options)).transported,
      true
    );
    const received = JSON.parse(readFileSync(receipt, 'utf8'));
    assert.equal(received.args.length, 2);
    assert.equal(received.args[0], '-c');
    assert(received.args[1].includes(JSON.stringify(state)));
    const generated = JSON.parse(run(['generate', '--output', join(path, 'same.pyz')], options));
    assert.equal(received.sha256, generated.sha256);
    assert.equal(existsSync(marker), false);
  } finally {
    rmSync(path, { recursive: true, force: true });
  }
});

test('unknown SSH switch results are reported without automatic retry', () => {
  const path = fixture(),
    receipt = join(path, 'ssh-count');
  try {
    writeFileSync(
      join(path, 'bin/ssh'),
      `#!${process.execPath}
require('fs').appendFileSync(${JSON.stringify(receipt)}, 'attempt\\n');process.exit(74);
`,
      { mode: 0o755 }
    );
    const result = spawnSync(
      process.execPath,
      [
        cli,
        'jupyter',
        'patch',
        'apply',
        '--ssh',
        'fixture',
        '--container',
        'owned-fixture',
        '--restart',
      ],
      { encoding: 'utf8', cwd: path, env: { ...process.env, PATH: join(path, 'bin') } }
    );
    assert.notEqual(result.status, 0);
    assert.match(result.stderr, /inspect status before any retry/);
    assert.equal(readFileSync(receipt, 'utf8'), 'attempt\n');
  } finally {
    rmSync(path, { recursive: true, force: true });
  }
});

test('deployment selects an explicit environment or container, with no machine-specific defaults', async () => {
  const { remoteCommand } = await import('../../bin/jupyter-patch.js');
  const plain = remoteCommand(
    { action: 'prepare', python: '/custom/venv with spaces/bin/python' },
    '0'.repeat(64)
  );
  assert(plain.startsWith("'/custom/venv with spaces/bin/python' -c "));
  assert(!plain.includes('--container'));
  assert(!plain.includes('jupyter-gpu-1'));
  const compose = remoteCommand(
    { action: 'prepare', container: 'chosen', python: '/custom/python' },
    '0'.repeat(64)
  );
  assert(compose.startsWith("'python3' -c "));
  assert(compose.includes('["prepare","--container","chosen","--python","/custom/python"]'));
});

function terminalFixture(closeEarly = false, forbidden = false) {
  const calls = [],
    commands = [];
  let received, socketHeaders;
  class Socket extends EventEmitter {
    constructor(url, options) {
      super();
      socketHeaders = options.headers;
      queueMicrotask(() => this.emit('open'));
    }
    send(message) {
      const [kind, command] = JSON.parse(message);
      assert.equal(kind, 'stdin');
      commands.push(command);
      if (commands.length === 1) {
        if (closeEarly) return queueMicrotask(() => this.emit('close'));
        const encoded = command.match(/[A-Za-z0-9+/=]{100,}/)[0];
        const script = inflateSync(Buffer.from(encoded, 'base64')).toString('utf8');
        this.ready = script.match(/REPAIR_READY_[a-z0-9]+/)[0];
        this.receipt = script.match(/REPAIR_RESULT_[a-z0-9]+/)[0];
        // POSIX shells can prefix Python's first line with bracketed-paste
        // control sequences. The marker must still be recognized once only.
        queueMicrotask(() =>
          this.emit(
            'message',
            Buffer.from(JSON.stringify(['stdout', '\x1b[?2004l\r' + this.ready + '\r\n']))
          )
        );
      } else if (command.trim() === this.receipt) {
        received = Buffer.from(commands.slice(1, -1).join('').replaceAll('\n', ''), 'base64');
        const output =
          this.receipt +
          JSON.stringify({ ok: true, result: { phase: 'prepared', deployment: 'environment' } }) +
          '\r\n';
        const middle = Math.floor(output.length / 2);
        queueMicrotask(() => {
          this.emit('message', Buffer.from(JSON.stringify(['stdout', output.slice(0, middle)])));
          this.emit('message', Buffer.from(JSON.stringify(['stdout', output.slice(middle)])));
        });
      } else {
        assert(command.length <= 1025, 'PTY lines must remain bounded');
      }
    }
    terminate() {
      this.emit('close');
    }
  }
  const client = {
    async response(route, method) {
      calls.push([route, method]);
      return {
        ok: !forbidden,
        status: forbidden ? 403 : method === 'DELETE' ? 204 : 200,
        body: { async cancel() {} },
      };
    },
    async responseText() {
      return JSON.stringify({ name: 'owned-terminal' });
    },
    async socket(route) {
      calls.push([route, 'WS']);
      return {
        url: 'ws://owned.invalid/prefix/' + route,
        headers: { Cookie: 'host-private-cookie' },
      };
    },
  };
  return {
    client,
    WebSocket: Socket,
    calls,
    commands,
    received: () => received,
    headers: () => socketHeaders,
  };
}

test('Terminal streams the same repair with bounded PTY lines, handles fragmented/control output and closes only its own terminal', async () => {
  const fixture = terminalFixture(),
    patch = buildPatch();
  const result = await deployTerminal({ action: 'prepare' }, patch, ['prepare'], fixture);
  assert.equal(result.transport, 'jupyter-terminal');
  assert.equal(result.artifactSha256, sha(patch.bytes));
  assert.deepEqual(fixture.received(), patch.bytes);
  assert.equal(fixture.headers().Cookie, 'host-private-cookie');
  assert(!fixture.commands.join('').includes('host-private-cookie'));
  assert.deepEqual(fixture.calls, [
    ['api/terminals', 'POST'],
    ['terminals/websocket/owned-terminal', 'WS'],
    ['api/terminals/owned-terminal', 'DELETE'],
  ]);
});

test('Terminal connection failure does not replay preparation and still closes its owned terminal', async () => {
  const fixture = terminalFixture(true);
  await assert.rejects(
    deployTerminal({ action: 'status' }, buildPatch(), ['status'], fixture),
    /before a verified receipt/
  );
  assert.equal(fixture.commands.length, 1);
  assert.equal(fixture.calls.filter(([, method]) => method === 'POST').length, 1);
  assert.deepEqual(fixture.calls.at(-1), ['api/terminals/owned-terminal', 'DELETE']);
});

test('Disabled/unauthorized terminals fail without a socket or deleting an unknown terminal', async () => {
  const fixture = terminalFixture(false, true);
  await assert.rejects(
    deployTerminal({ action: 'prepare' }, buildPatch(), ['prepare'], fixture),
    /HTTP 403/
  );
  assert.deepEqual(fixture.calls, [['api/terminals', 'POST']]);
  assert.equal(fixture.commands.length, 0);
});
